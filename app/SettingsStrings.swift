    /// Localised string for a web i18n key. `vars` replaces {name} placeholders.
    static func t(_ key: String, lang: SettingsLanguage, vars: [String: String] = [:]) -> String {
        let arr = table[key] ?? [key, key, key]
        var s = arr[lang.i18nIndex]
        for (k, v) in vars { s = s.replacingOccurrences(of: "{" + k + "}", with: v) }
        return s
    }
